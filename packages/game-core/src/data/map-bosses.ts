/** 造一条守关 BOSS（统一 `camp: 'enemy'` + `gold` 必掉，`rate = 1`）。 */
function bossEntry(input: {
  key: string;
  name: string;
  description: string;
  maxHp: number;
  atk: number;
  atkSpeed: number;
  exp: number;
  def?: number;
  level: number;
  skills: Array<{ key: string; level: number }>;
  buffs?: Array<{ type: string }>;
  gold: [number, number];
  originKey: string;
}): EnemyEntry {
  return {
    key: input.key,
    name: input.name,
    description: input.description,
    camp: 'enemy',
    race: 'unknown',
    career: 'melee',
    maxHp: input.maxHp,
    atk: input.atk,
    atkSpeed: input.atkSpeed,
    exp: input.exp,
    ...(input.def !== undefined ? { def: input.def } : {}),
    level: input.level,
    skills: input.skills,
    ...(input.buffs !== undefined ? { buffs: input.buffs } : {}),
    affixes: { ...AFFIXES },
    loots: [{ key: 'gold', count: input.gold, rate: 1 }],
    originKey: input.originKey,
  };
}

